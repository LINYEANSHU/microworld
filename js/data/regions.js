  // 生成稀疏连接。rng 仅用于在同等近邻中做确定性挑选。
  MW.buildLinks = function (rng) {
    var R = MW.REGIONS, i, j, a, b;
    var seen = {}, links = [];
    function addLink(a, b, type) {
      if (a === b) return;
      var key = a < b ? a + '_' + b : b + '_' + a;
      if (seen[key]) { // 同对多通道: 保留优先级 陆<海<空 中的高者, 并重算速率
        var l = seen[key];
        if (type > l.type) {
          l.type = type;
          var xa = R[l.a], xb = R[l.b];
          var dd = MW.U.distKM(xa.lon, xa.lat, xb.lon, xb.lat);
          var pp = PHI_BASE[type];
          if (isFinite(PHI_DIST[type])) pp *= Math.sqrt(1200 / Math.max(600, dd)) * 1.9;
          pp *= 0.65 + 0.12 * (xa.wealth + xb.wealth) + 0.06 * (xa.urb + xb.urb);
          l.phi = pp;
        }
        return;
      }
      var la = R[a], lb = R[b];
      var d = MW.U.distKM(la.lon, la.lat, lb.lon, lb.lat);
      var phi = PHI_BASE[type];
      if (isFinite(PHI_DIST[type])) phi *= Math.sqrt(1200 / Math.max(600, d)) * 1.9;
      phi *= 0.65 + 0.12 * (la.wealth + lb.wealth) + 0.06 * (la.urb + lb.urb);
      var link = { a: Math.min(a, b), b: Math.max(a, b), type: type, phi: phi, d: d };
      seen[key] = link; links.push(link);
    }
    // 陆路
    for (i = 0; i < MW.LAND_EDGES.length; i++) addLink(MW.LAND_EDGES[i][0], MW.LAND_EDGES[i][1], 0);
    // 海路: 沿海区域 → 最近沿海枢纽（hub0 取1条, hub≥1 取2条, 距离>900km）
    var seaHubs = [];
    for (i = 0; i < R.length; i++) if (R[i].coast && R[i].hub >= 1) seaHubs.push(i);
    function nearestHubs(src, hubs, k, minD) {
      var cand = [];
      for (var x = 0; x < hubs.length; x++) {
        if (hubs[x] === src) continue;
        var d = MW.U.distKM(R[src].lon, R[src].lat, R[hubs[x]].lon, R[hubs[x]].lat);
        if (d >= minD) cand.push([d, hubs[x]]);
      }
      cand.sort(function (p, q) { return p[0] - q[0] || p[1] - q[1]; });
      return cand.slice(0, k).map(function (c) { return c[1]; });
    }
    for (i = 0; i < R.length; i++) {
      if (!R[i].coast) continue;
      var k = R[i].hub >= 1 ? 2 : 1;
      var hs = nearestHubs(i, seaHubs, k, 900);
      for (j = 0; j < hs.length; j++) addLink(i, hs[j], 1);
    }
    // 空路: hub2 全互联 + hub1 连最近 hub2 + 富裕非枢纽连最近枢纽
    var hub2 = [];
    for (i = 0; i < R.length; i++) if (R[i].hub === 2) hub2.push(i);
    for (i = 0; i < hub2.length; i++)
      for (j = i + 1; j < hub2.length; j++) addLink(hub2[i], hub2[j], 2);
    for (i = 0; i < R.length; i++) {
      if (R[i].hub === 1) { addLink(i, nearestHubs(i, hub2, 1, 0)[0], 2); }
      else if (R[i].hub === 0 && R[i].wealth === 2) {
        var near = nearestHubs(i, hub2.concat(R.filter(function (r) { return r.hub === 1; }).map(function (r) { return r.id; })), 1, 0);
        if (near.length) addLink(i, near[0], 2);
      }
    }
    // 统一排序保证确定性
    links.sort(function (p, q) { return (p.a - q.a) || (p.b - q.b) || (p.type - q.type); });
    for (i = 0; i < links.length; i++) { links[i].id = i; links[i].cls = [1, 1, 1]; } // 陆/海/空 封锁乘数
    return links;
  };

